const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const root = path.resolve(__dirname, "..");
const output = path.join(root, "src/styles/uicons.css");
const fontDirectory = path.join(root, "src/styles/uicons");
const packageCss = path.join(
  root,
  "node_modules/@flaticon/flaticon-uicons/css"
);

const collectIcons = (directory, icons) => {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) collectIcons(filename, icons);
    else if (/\.(js|jsx|ts|tsx|css)$/.test(entry.name) && filename !== output) {
      for (const match of fs
        .readFileSync(filename, "utf8")
        .matchAll(/\bfi-(?:rr|rs|sr|ss|br|bs|brands)-[a-z0-9-]+/g))
        icons.add(match[0]);
    }
  }
};

const getIconData = () => {
  // The slider constructs these two class names at runtime.
  const icons = new Set(["fi-rr-angle-small-left", "fi-rr-angle-small-right"]);
  collectIcons(path.join(root, "src"), icons);
  collectIcons(path.join(root, "pages"), icons);
  const groups = [];
  for (const family of ["regular", "bold", "solid", "brands"]) {
    const css = fs.readFileSync(
      path.join(packageCss, family, "all.css"),
      "utf8"
    );
    const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)];
    for (const [, selector, declarations] of rules) {
      if (selector !== "@font-face") continue;
      const name = declarations.match(/font-family:([^;]+)/)[1];
      const source = declarations.match(/src:url\(\.\.\/([^)]+\.woff2)\)/)[1];
      const prefix = {
        "uicons-regular-rounded": "rr",
        "uicons-regular-straight": "rs",
        "uicons-bold-rounded": "br",
        "uicons-bold-straight": "bs",
        "uicons-solid-rounded": "sr",
        "uicons-solid-straight": "ss",
        "uicons-brands": "brands",
      }[name];
      const glyphs = rules.flatMap(([full, ruleSelector, body]) => {
        const match = ruleSelector.match(/^\.(fi-[a-z]+-[a-z0-9-]+):before$/);
        return match &&
          icons.has(match[1]) &&
          match[1].startsWith(`fi-${prefix}-`)
          ? [
              {
                name: match[1],
                codepoint: parseInt(body.match(/\\([0-9a-f]+)/)[1], 16),
                css: full,
              },
            ]
          : [];
      });
      if (!glyphs.length) continue;
      groups.push({
        name,
        prefix,
        source,
        sha256: crypto
          .createHash("sha256")
          .update(fs.readFileSync(path.join(packageCss, source)))
          .digest("hex"),
        glyphs: glyphs.sort((a, b) => a.name.localeCompare(b.name)),
        base: rules.find(([, s]) =>
          s.startsWith(`i[class^=fi-${prefix}-]`)
        )?.[0],
      });
    }
  }
  return groups;
};

const generate = () => {
  const groups = getIconData();
  const manifestPath = path.join(fontDirectory, "manifest.json");
  const subsets = fs.existsSync(manifestPath)
    ? JSON.parse(fs.readFileSync(manifestPath, "utf8"))
    : {};
  const css = [
    "/* Generated by scripts/generate-uicons.cjs from the installed Flaticon package. */",
  ];
  for (const group of groups) {
    const subset = subsets[group.name];
    const canUseSubset =
      subset?.sha256 === group.sha256 &&
      group.glyphs.every(({ name }) => subset.icons.includes(name)) &&
      fs.existsSync(path.join(fontDirectory, subset.file));
    // New icons or package upgrades safely use the original font until the
    // optional subset regeneration is run. They never lose their glyphs.
    const font = canUseSubset
      ? `./uicons/${subset.file}`
      : `../../node_modules/@flaticon/flaticon-uicons/css/${group.source}`;
    css.push(
      `@font-face{font-family:${group.name};src:url(${font}) format("woff2");font-display:swap}`
    );
    css.push(group.base, ...group.glyphs.map(({ css }) => css));
  }
  const content = css.join("\n") + "\n";
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== content) {
    fs.writeFileSync(output, content);
  }
  console.log(
    `UIcons: ${groups.reduce(
      (sum, g) => sum + g.glyphs.length,
      0
    )} icons, ${Buffer.byteLength(content)} CSS bytes`
  );
};

module.exports = { getIconData, generate };
if (require.main === module) {
  if (process.argv.includes("--manifest"))
    process.stdout.write(JSON.stringify(getIconData()));
  else generate();
}
